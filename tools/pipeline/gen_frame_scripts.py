#!/usr/bin/env python3
"""Translate the timeline-only MBFZ_fla.* classes (pure frame scripts) into
src/game/timelineScripts.ts, which registers them by symbol id in SwfClip.scripts.

The AS3 bodies are tiny and formulaic; each statement is translated with explicit rules
and the script fails loudly on anything it does not recognise.
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'extracted', 'scripts', 'scripts', 'MBFZ_fla')
LIB = os.path.join(ROOT, 'public', 'assets', 'library.json')
OUT = os.path.join(ROOT, 'src', 'game', 'timelineScripts.ts')

RULES = [
    (r'^stop\(\);$', 'c.stop();'),
    (r'^prevFrame\(\);$', 'c.prevFrame();'),
    (r'^gotoAndPlay\((\d+)\);$', r'c.gotoAndPlay(\1);'),
    (r'^gotoAndStop\(UnitMC\(parent\.parent\)\.getWeaponID\(\)\);$', 'c.gotoAndStop((c.parent!.parent as any).getWeaponID());'),
    (r'^gotoAndStop\(UT\.irand\(1,totalFrames\)\);$', 'c.gotoAndStop(UT.irand(1, c.totalFrames));'),
    (r'^gotoAndStop\(uint\(Math\.random\(\) \* (\d+)\) \+ 1\);$', r'c.gotoAndStop(uint(Math.random() * \1) + 1);'),
    (r'^MovieClip\(parent\)\.(\w+)\(\);$', r'(c.parent as any).\1();'),
    (r'^MovieClip\(parent\)\.(\w+)\(this\.(\w+)\);$', r"(c.parent as any).\1(c.child('\2'));"),
    (r'^(Menu|Cutscene|Arena)\(parent\)\.(\w+)\(([\d]*)\);$', r'(c.parent as any).\2(\3);'),
    (r'^Menu\(parent\.parent\)\.setTeams\(this,(\d)\);$', r'(c.parent!.parent as any).setTeams(c, \1);'),
    (r'^Cutscene\(parent\)\.(\w+)\.visible = (true|false);$', r'(c.parent as any).\1.visible = \2;'),
    (r'^SH\.playSound\((\w+)\);$', r"SH.playSound('\1');"),
    (r'^Stats_Achievements\.setAchievement\("(\w+)"\);$', r"Stats_Achievements.setAchievement('\1');"),
    (r'^this\.(\w+)\.text = "([^"]*)";$', r"c.child<SwfTextField>('\1').text = '\2';"),
    (r'^this\.(\w+)\.mask = this\.(\w+);$', r"setFlashMask(c.child('\1'), c.child('\2'));"),
    (r'^this\.txt_letter\.text = NodeHoldpoint\(parent\.parent\)\.letter;$', "c.child<SwfTextField>('txt_letter').text = (c.parent!.parent as any).letter;"),
]


def translate(stmt, where):
    for pat, rep in RULES:
        if re.match(pat, stmt):
            return re.sub(pat, rep, stmt)
    sys.exit(f'untranslated statement in {where}: {stmt!r}')


def statements(body):
    out = []
    for line in body.strip().splitlines():
        line = line.strip()
        if line:
            out.append(line)
    return out


def main():
    lib = json.load(open(LIB))
    classes = lib['classes']
    entries = []
    for fn in sorted(os.listdir(SRC)):
        name = fn[:-3]
        cls = f'MBFZ_fla.{name}'
        if cls not in classes:
            sys.exit(f'{cls} not in library')
        src = open(os.path.join(SRC, fn)).read()
        frames = {}
        for num, body in re.findall(r'internal function frame(\d+)\(\) : \*\s*\{(.*?)\n      \}', src, re.S):
            frames[int(num)] = [translate(s, f'{name}.frame{num}') for s in statements(body)]
        # addFrameScript(index0, this.frameN, ...) maps 0-based frame index to function
        afs = re.search(r'addFrameScript\(([^;]*)\);', src)
        mapping = {}
        if afs:
            parts = [p.strip() for p in afs.group(1).split(',')]
            for i in range(0, len(parts), 2):
                mapping[int(parts[i]) + 1] = int(re.search(r'frame(\d+)', parts[i + 1]).group(1))
        if not mapping:
            continue
        entries.append((cls, classes[cls], {f: frames[fn_] for f, fn_ in sorted(mapping.items())}))

    lines = [
        '// GENERATED by tools/pipeline/gen_frame_scripts.py from the MBFZ_fla.* timeline classes.',
        '// Do not edit by hand; re-run the generator.',
        "import { uint } from '../flash/as3';",
        "import { SwfClip, setFlashMask, type FrameScript, type SwfTextField } from '../swf/display';",
        "import { UT } from './UT';",
        "import { SH } from './SH';",
        "import { Stats_Achievements } from './Stats_Achievements';",
        '',
        'const scripts: [number, string, Record<number, FrameScript>][] = [',
    ]
    for cls, cid, frames in entries:
        lines.append(f'  [{cid}, {json.dumps(cls)}, {{')
        for f, stmts in frames.items():
            body = ' '.join(stmts)
            lines.append(f'    {f}: (c) => {{ {body} }},')
        lines.append('  }],')
    lines += [
        '];',
        '',
        '/** Register frame scripts for timeline-only symbols (call once at boot). */',
        'export function registerTimelineScripts(): void {',
        '  for (const [id, , frames] of scripts) {',
        '    SwfClip.scripts.set(id, new Map(Object.entries(frames).map(([f, fn]) => [Number(f), fn])));',
        '  }',
        '}',
        '',
    ]
    open(OUT, 'w').write('\n'.join(lines))
    print(f'wrote {len(entries)} classes to {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
